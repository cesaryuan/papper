"""
Pandoc filter to adjust Table and Figure.

1. Support two column layout for Table and Figure with attribute `twocol=true`
2. Remove autogenerated "Figure " or "Table " prefix from caption
3. Using table instead of longtable (default in Pandoc) for Table, which is not supported in double-column layout. AI conversion is not used.
"""

