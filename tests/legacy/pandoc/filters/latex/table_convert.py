def extract_text_from_inlines(inlines) -> str:
    """Extract plain text from panflute inline elements."""
    if not inlines:
        return ""
    
    result = []
    for elem in inlines:
        if isinstance(elem, pf.Str):
            # Escape special LaTeX characters
            text = elem.text
            text = text.replace('\\', '\\textbackslash{}')
            text = text.replace('_', '\\_')
            text = text.replace('%', '\\%')
            text = text.replace('$', '\\$')
            text = text.replace('#', '\\#')
            text = text.replace('&', '\\&')
            text = text.replace('{', '\\{')
            text = text.replace('}', '\\}')
            result.append(text)
        elif isinstance(elem, pf.Space):
            result.append(' ')
        elif isinstance(elem, pf.Quoted):
            inner = extract_text_from_inlines(elem.content)
            result.append(f"\"{inner}\"")
        elif isinstance(elem, pf.Strong):
            # Handle bold text
            inner = extract_text_from_inlines(elem.content)
            result.append(f"\\textbf{{{inner}}}")
        elif isinstance(elem, pf.Emph):
            # Handle italic text
            inner = extract_text_from_inlines(elem.content)
            result.append(f"\\textit{{{inner}}}")
        elif isinstance(elem, pf.Code):
            result.append(f"\\texttt{{{elem.text}}}")
        elif isinstance(elem, pf.Math):
            if elem.format == "InlineMath":
                result.append(f"${elem.text}$")
            else:
                result.append(f"$${elem.text}$$")
        elif isinstance(elem, pf.Image):
            # Handle images in table cells
            # width = elem.attributes.get('width', '15%')
            # # Convert percentage to linewidth fraction
            # if '%' in width:
            #     fraction = float(width.replace('%', '')) / 100
            #     width_spec = f"{fraction:.2f}\\linewidth"
            # else:
            #     width_spec = width
            # result.append(f"\\includegraphics[width={width_spec}]{{{elem.url}}}")
            
            # 对于表格中的图片，我们在 extract_table_info 函数中使用了 m{2.8cm} 
            # 来解决图片列垂直居中的问题，而这会导致 \\linewidth 指向的是单元格的宽度
            # 而不是页面行的宽度，因此需要将宽度固定为 0.95\\linewidth
            result.append(f"\\includegraphics[width=0.95\\linewidth]{{{elem.url}}}")
        elif isinstance(elem, pf.RawInline):
            if elem.format == 'latex':
                result.append(elem.text)
        else:
            # Fallback: stringify
            pf.debug(f"Fallback: stringify {elem}")
            result.append(pf.stringify(elem))
    
    return ''.join(result)


def extract_table_info(table: pf.Table) -> dict:
    """Extract structured information from a panflute Table element."""
    info = {
        'caption': '',
        'label': '',
        'headers': [],
        'alignment': [],
        'rows': [],
        'attrs': {}
    }
    
    info['attrs'] = table.attributes
    
    if table.caption:
        caption_text = pf.stringify(table.caption)
        info['caption'] = caption_text
        
    if table.identifier:
        info['label'] = table.identifier
    
    if table.colspec:
        for align, _ in table.colspec:
            if align == 'AlignLeft':
                info['alignment'].append('l')
            elif align == 'AlignRight':
                info['alignment'].append('r')
            elif align == 'AlignCenter':
                info['alignment'].append('c')
            else:
                info['alignment'].append('l')  # default
            
    
    # Extract headers from table head
    if table.head and table.head.content:
        for row in table.head.content:
            if hasattr(row, 'content'):
                header_row = []
                for cell in row.content:
                    if hasattr(cell, 'content'):
                        cell_content = []
                        for block in cell.content:
                            if isinstance(block, pf.Para) or isinstance(block, pf.Plain):
                                cell_content.append(extract_text_from_inlines(block.content))
                        header_row.append(' '.join(cell_content))
                if header_row:
                    info['headers'] = header_row
                    break  # Only take first header row
    
    # Extract data rows from table body
    if hasattr(table, 'content'):
        for body in table.content:
            if hasattr(body, 'content'):
                for row in body.content:
                    if hasattr(row, 'content'):
                        data_row = []
                        for cell in row.content:
                            if hasattr(cell, 'content'):
                                cell_content = []
                                for block in cell.content:
                                    if isinstance(block, pf.Para) or isinstance(block, pf.Plain):
                                        cell_content.append(extract_text_from_inlines(block.content))
                                data_row.append(' '.join(cell_content))
                        if data_row:
                            info['rows'].append(data_row)
    
    # 对于包含图片列的表格，图片所在的行中，其他列的文字会无法垂直居中
    # m{2.8cm} 可以解决这个问题
    # 参考 https://blog.csdn.net/happy_demo/article/details/105430091
    for i in range(len(info['alignment'])):
        if any('\\includegraphics' in row[i] for row in info['rows']):
            info['alignment'][i] = 'm{2.8cm}'
            
    return info


def convert_table_with_ai(markdown_table: str) -> Optional[str]:
    """Use Gemini AI to convert table information to LaTeX."""
    if not GEMINI_AVAILABLE or GEMINI_CLIENT is None:
        return None
    
    try:
        prompt = CONVERSION_PROMPT.replace(
            '{style_examples}', LATEX_STYLE_EXAMPLES,
        ).replace(
            '{markdown_table}', markdown_table
        )
        
        # Prepare content for the new API
        contents: list[ContentUnionDict] = [
            types.Content( 
                role="user",
                parts=[
                    types.Part.from_text(text=prompt),
                ],
            ),
        ]
        
        # Configure generation
        generate_content_config = types.GenerateContentConfig(
            temperature=0.3,  # Lower temperature for more consistent formatting
            max_output_tokens=4096,
            thinking_config=types.ThinkingConfig(
                thinking_budget=0,
            ),
            http_options=types.HttpOptions(
                retry_options=types.HttpRetryOptions(
                    attempts=3
                ),
            ),
        )
        
        # Call Gemini API using the new client
        model = "gemini-flash-latest"
        response_chunks = []
        
        for chunk in GEMINI_CLIENT.models.generate_content_stream(
            model=model,
            contents=contents,
            config=generate_content_config,
        ):
            if chunk.text:
                response_chunks.append(chunk.text)
        # print cached token
        if chunk and chunk.usage_metadata:  # pyright: ignore[reportPossiblyUnboundVariable]
            pf.debug(f"Cached token: {chunk.usage_metadata.cached_content_token_count}")
        
        # Combine all chunks
        latex_code = ''.join(response_chunks).strip()
        
        # Clean up the response (remove markdown code blocks if present)
        if latex_code.startswith('```'):
            lines = latex_code.split('\n')
            latex_code = '\n'.join(lines[1:-1] if len(lines) > 2 else lines)
        
        # Remove any remaining markdown artifacts
        latex_code = latex_code.replace('```latex', '').replace('```', '').strip()
        
        pf.debug("Successfully converted table with AI")
        return latex_code
        
    except Exception as e:
        pf.debug(f"Error converting table with AI: {str(e)}")
        return None


def fallback_table_conversion(table_info: dict) -> str:
    """Fallback: Generate basic LaTeX table if AI conversion fails."""
    caption = table_info['caption']
    label = table_info['label']
    headers = table_info['headers']
    alignment = table_info['alignment'] if table_info['alignment'] else ['l'] * len(headers)
    rows = table_info['rows']
    
    # Determine if we need table* (wide table)
    num_cols = len(headers)
    table_env = 'table*' if num_cols > 5 or 'includegraphics' in rows.__str__() else 'table'
    if 'twocol' in table_info['attrs']:
        table_env = 'table' if table_info['attrs']['twocol'] == 'false' else 'table*'
    
    # Build LaTeX
    latex_lines = [
        f"\\begin{{{table_env}}}[htbp]",
        "\\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        f"\\begin{{tabular}}{{{(' '.join(alignment))}}}",
        "\\toprule",
    ]
    
    # Add headers
    if headers:
        header_line = ' & '.join([f"\\textbf{{{h}}}" for h in headers])
        latex_lines.append(header_line + " \\\\")
        latex_lines.append("\\midrule")
    
    # Add rows
    for row in rows:
        row_line = ' & '.join(row)
        latex_lines.append(row_line + " \\\\")
    
    latex_lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
        f"\\end{{{table_env}}}"
    ])
    
    return '\n'.join(latex_lines)


def action(elem: pf.Element, doc: pf.Doc) -> Optional[pf.Element]:
    """
    Panflute action function to process each element.
    
    Args:
        elem: The element to process
        doc: The document
    
    Returns:
        Modified element or None
    """
    # Only process tables when outputting to LaTeX
    if 'debugpy' not in sys.modules and doc.format != 'latex':
        return None
    
    if isinstance(elem, pf.Caption) and (pf.stringify(elem).startswith('Figure ') or pf.stringify(elem).startswith('Table ')):
        elem.content.list[0].content = elem.content.list[0].content[4:]

    if isinstance(elem, pf.Figure):
        image_elem = elem.content.list[0].content.list[0]
        latex = cast(str, pf.convert_text(elem, input_format='panflute', output_format='latex'))
        if 'twocol' in image_elem.attributes and image_elem.attributes['twocol'] == 'true':
            # 双栏展示图片
            latex = latex.replace('{figure}', '{figure*}')
        else:
            # Latex 中在双栏模式下， \\textwidth 为单栏的宽度
            # 因此对于所有不双栏展示的图片，宽度都设置为 95%，否则图片会很小
            image_elem.attributes['width'] = '95%'
            return None
        return pf.RawBlock(latex, format='latex')
        
    if isinstance(elem, pf.Table):
        latex_code = None
        table_info = extract_table_info(elem)
        
        if not table_info['headers'] and not table_info['rows']:
            log_warning("Warning: Empty table found, skipping.")
            return None
        
        # Try AI conversion first
        # markdown_table: str = cast(str, pf.convert_text(elem, input_format='panflute', output_format='markdown'))
        # latex_code = convert_table_with_ai(markdown_table)
        
        # Fallback to basic conversion if AI fails
        if latex_code is None:
            # print("Using fallback table conversion...", file=sys.stderr)
            latex_code = fallback_table_conversion(table_info)
        
        # Return as RawBlock
        return pf.RawBlock(latex_code, format='latex')
    
    return None


def prepare(doc: pf.Doc) -> None:
    if doc.format == 'latex':
        log_debug("Table conversion filter initialized.")
        if not GEMINI_AVAILABLE:
            log_warning("WARNING: Gemini API not available. Using fallback conversion.")


def finalize(doc: pf.Doc) -> None:
    pass


def main(doc: pf.Doc | None = None):
    return pf.run_filter(
        action,
        prepare=prepare,
        finalize=finalize,
        doc=doc
    )


